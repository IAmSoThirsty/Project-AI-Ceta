"""Compare real Python/Rust parsers and canonical bytes using frozen vectors.

This is serializer qualification. It does not exercise authority, isolation,
effect execution, or independent human review.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import random
import struct
import subprocess
import sys
import unicodedata

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from ceta.contracts import ContractError, canonical_bytes, strict_loads


def vectors() -> list[bytes]:
    result = [b'null', b'true', b'false', b'0', b'-0', b'9223372036854775807',
              b'-9223372036854775808', b'{}', b'[]',
              b'{"z":1,"a":[true,null,-2]}', b'{"a":1,"a":2}',
              b'{"nested":{"a":1,"a":2}}', b'1.0', b'-0.0', b'1e0',
              b'1E3', b'NaN', b'Infinity', b'9223372036854775808',
              b'-9223372036854775809', b'{}{}', b'"\\ud800"', b'"\\udfff"',
              b'"\\ud800\\ud800"', b'"\\ud83d\\ude00"', b'"\\xff"', b'\xff',
              b'"e\\u0301"', b'"\\u00e9"', b'"\\u212b"',
              b'{"\\u0061":1,"a":2}', b'"[,]{}"', b'"\\u0000\\n\\t\\b\\f\\r"',
              b'[' * 32 + b'0' + b']' * 32,
              b'[' * 33 + b'0' + b']' * 33,
              b'"\x7f"', b'"\x00"', b'01', b'+1', b'1.', b'-',
              ' { "😀": 2, "\ue000": 1, "\u2028": "\u2029" } '.encode()]
    for path in sorted((ROOT / "contracts/examples").glob("*.json")):
        result.append(json.dumps(json.loads(path.read_bytes())["instance"], ensure_ascii=False).encode())
    event_vector = json.loads((ROOT / "contracts/vectors/event-preimage-v1.json").read_bytes())
    result.append(json.dumps(event_vector["instance"], ensure_ascii=False, indent=2).encode())
    # The expected event body was manually specified, not generated by either
    # serializer. Include deliberately reordered input for its native comparison.
    body = json.loads(event_vector["expected_body"])
    result.append(json.dumps(dict(reversed(list(body.items()))), indent=2).encode())
    # Every Unicode 15 scalar with canonical decomposition, including the full
    # Hangul decomposition range: test original and decomposed wire acceptance.
    for codepoint in range(0x110000):
        if 0xD800 <= codepoint <= 0xDFFF:
            continue
        character = chr(codepoint)
        decomposed = unicodedata.normalize("NFD", character)
        if character != decomposed:
            result.append(json.dumps(character, ensure_ascii=False).encode())
            result.append(json.dumps(decomposed, ensure_ascii=False).encode())
    rng = random.Random(601006)
    for _ in range(1000):
        record = {f"key-{rng.randrange(1000):04}": [rng.randrange(-(2**63), 2**63),
                  rng.choice([True, False, None, "é", "😀", "[{}]", "\u2028", "\x00"])]
                  for _ in range(rng.randrange(1, 12))}
        result.append(json.dumps(record, ensure_ascii=False, indent=2).encode())
    return result


def compare(binary: Path) -> dict:
    before = {str(path.relative_to(ROOT)): hashlib.sha256(path.read_bytes()).hexdigest()
              for path in (ROOT / "src/ceta/contracts/wire.py", Path(__file__),
                           ROOT / "contracts/vectors/event-preimage-v1.json",
                           ROOT / "native/canonical_reference/src/main.rs",
                           ROOT / "native/canonical_reference/Cargo.toml",
                           ROOT / "native/canonical_reference/Cargo.lock", binary)}
    identity = json.loads(subprocess.run([str(binary), "--identity"], capture_output=True,
                                         check=True).stdout)
    if identity["unicode"] != unicodedata.unidata_version:
        raise ValueError("Unicode table versions differ")
    wires = vectors()
    request = b"".join(struct.pack(">I", len(wire)) + wire for wire in wires)
    process = subprocess.run([str(binary)], input=request, capture_output=True, check=True, timeout=120)
    offset, failures, accepted, rejected = 0, [], 0, 0
    for index, wire in enumerate(wires):
        if offset + 4 > len(process.stdout):
            raise ValueError("reference output truncated")
        size = struct.unpack(">I", process.stdout[offset:offset + 4])[0]
        offset += 4
        reference = process.stdout[offset:offset + size] if size else None
        offset += size
        if size > 1024 * 1024 or offset > len(process.stdout):
            raise ValueError("reference output invalid")
        try:
            actual = canonical_bytes(strict_loads(wire))
            accepted += 1
        except ContractError:
            actual = None
            rejected += 1
        if actual != reference:
            failures.append({"index": index, "wire_sha256": hashlib.sha256(wire).hexdigest(),
                             "python": "REJECT" if actual is None else "ACCEPT",
                             "rust": "REJECT" if reference is None else "ACCEPT",
                             "same_canonical_bytes": actual == reference})
    if offset != len(process.stdout):
        raise ValueError("unexpected trailing reference frames")
    unchanged = all(hashlib.sha256((ROOT / name).read_bytes()).hexdigest() == sha
                    for name, sha in before.items())
    return {"scope": "TWO_REAL_SERIALIZER_IMPLEMENTATIONS", "profile": identity["profile"],
            "result": "PASS" if not failures and unchanged else "FAIL", "vectors": len(wires),
            "python_accepted": accepted, "python_rejected": rejected,
            "vector_input_sha256": hashlib.sha256(request).hexdigest(),
            "reference_output_sha256": hashlib.sha256(process.stdout).hexdigest(),
            "source_before_sha256": before, "source_unchanged": unchanged,
            "python": sys.version, "unicode": identity["unicode"], "failures": failures,
            "authority_qualification": "NOT_RUN", "independent_review": "NOT_PERFORMED"}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", type=Path,
                        default=ROOT / "native/canonical_reference/target/debug/ceta-canonical-reference.exe")
    args = parser.parse_args()
    result = compare(args.binary.resolve(strict=True))
    print(json.dumps(result, indent=2))
    return 0 if result["result"] == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
